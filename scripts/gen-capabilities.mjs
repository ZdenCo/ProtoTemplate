#!/usr/bin/env node
// Writes CAPABILITIES.md: what this app can use (connectors, recipes, UI kit) and which modules exist.
// Generated from src/core/connectors/*/meta.json, src/core/recipes/*/meta.json and vendor/protoshell.json.

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { connectors, moduleIds, moduleInfo, recipes, root, shellCapabilities } from './lib.mjs';

const shell = shellCapabilities();
const list = connectors();
const out = [];

out.push('# Capabilities', '');
out.push('> Generated by `npm run gen:capabilities`. Do not edit by hand.', '');
out.push('What an app built on this template can do on the phone. Every connector works in the browser too, with a mock.', '');

out.push('## Connectors', '');
out.push('Use in a block: `const api = useConnector(\'<id>\')` (from `@core`). Declare required ones in `requires.capabilities` of `defineModule`, optional ones in `optional.capabilities` and check `useCapability(\'<id>\')`.', '');
out.push('| id | What | In shell |', '| --- | --- | --- |');
for (const c of list) out.push(`| \`${c.id}\` | ${c.title} | ${shell.has(c.id) ? 'yes' : '**no**'} |`);
out.push('');

for (const c of list) {
  out.push(`### \`${c.id}\` — ${c.title}${c.core ? ' (core, always present)' : ''}`, '');
  out.push(c.summary, '');
  if (c.limits?.length) out.push('Limits:', '', ...c.limits.map((l) => `- ${l}`), '');
  out.push('```tsx', c.example, '```', '');
  out.push(`Full typed API: \`src/core/connectors/${c.id}/api.ts\`. Mock fixtures: ${c.mocks}.`, '');
}

out.push('## Recipes', '');
out.push('Ready-made hooks/components combining connectors. Import from `@core/recipes/<id>`.', '');
for (const r of recipes()) {
  out.push(`### \`${r.id}\` — ${r.title}`, '');
  out.push(r.summary, '');
  out.push(`Exports: ${r.hooks.map((h) => `\`${h}\``).join(', ')}. Uses connectors: ${r.connectors.length ? r.connectors.map((c) => `\`${c}\``).join(', ') : 'none'}.`, '');
  out.push('```tsx', r.example, '```', '');
}

out.push('## Core hooks (`@core`)', '');
out.push(
  '| Hook | Purpose |',
  '| --- | --- |',
  '| `useConnector(id)` | Typed device API (real in ProtoShell, mock in browser). |',
  '| `useCapability(id)` | `true` if the capability is usable now. |',
  '| `useSubscription(subscribe, deps, { enabled })` | Run a streaming subscription while mounted (sensors, GPS, BLE). |',
  '| `useStoredState(key, initial)` | `useState` persisted per module. |',
  '| `useModuleStorage()` | Namespaced key/value store (`get/set/getJSON/setJSON/keys/clear`). |',
  '| `useBlobStore()` | IndexedDB blobs (photos); `toBlob(photo.webPath)`. |',
  '| `persistStorage(moduleId)` | Storage for zustand `persist`. |',
  '| `useModuleSettings()` | `[values, update]` of the module `settings` schema. |',
  '| `useNav()` | `toPage(key)`, `toRoute(path)` (module routes), `back()`. |',
  '| `useRouteParams()` | Params of a module route. |',
  '| `useEmit()` / `useEvent(name, handler)` | Typed events between modules. |',
  '| `useFlag(name)` | Read a feature flag. |',
  '| `usePlatform(s => s.mode)` | `\'shell\'` or `\'mock\'`. |',
  '| `toast.success/error/info(msg)` | Feedback messages. |',
  '| `appConfig` | App id, name, version. |',
  '',
  'Errors from connectors: `UserCancelledError` (ignore), `PermissionDeniedError`, `CapabilityUnavailableError`, `DeviceUnsupportedError`, `TimeoutError`, `CoreError`.',
  '',
);

out.push('## UI kit (`@core/ui`)', '');
out.push(
  '`Card`, `Row`, `Stack`, `Text`, `Badge`, `Button`, `AsyncButton` (spinner + error toast, the default for connector calls), `List`, `ListItem`, `Field`, `Input`, `TextArea`, `Select`, `Toggle`, `Slider`, `Sheet`, `ProgressBar`, `Spinner`, `StreamingText`, `Thumbnail`, `EmptyState`, `ErrorState`, `Divider`, `cn`. Pages only: `PageLayout`, `Zone`.',
  '',
  'Tailwind tokens: `bg-bg`, `bg-surface`, `bg-surface-2`, `border-line`, `text-text`, `text-muted`, `bg-accent`, `text-on-accent`, `text-success`, `text-warning`, `text-danger`, `rounded-card`; safe areas: `pt-safe`, `pb-safe`, `px-safe`.',
  '',
);

out.push('## Modules in this app', '');
const ids = moduleIds();
if (!ids.length) out.push('None yet.', '');
for (const id of ids) {
  const m = moduleInfo(id);
  out.push(`- \`${m.id}\` — ${m.title}: ${m.description}`);
}
out.push('');

const missing = list.filter((c) => !shell.has(c.id)).map((c) => c.id);
if (missing.length) out.push(`> Warning: not in the vendored ProtoShell build: ${missing.join(', ')}. Run \`npm run sync:shell\`.`, '');

writeFileSync(join(root, 'CAPABILITIES.md'), out.join('\n'));
console.log(`CAPABILITIES.md: ${list.length} connectors, ${recipes().length} recipes, ${ids.length} modules`);
