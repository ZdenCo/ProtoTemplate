function filterJobsByQuery(jobs: Job[], query: SearchQuery): Job[] {
  if (!query.role.trim() && (!query.keywords || query.keywords.length === 0)) {
    return jobs;
  }

  const allSearchTerms = [
    query.role,
    ...query.synonyms,
    ...(query.keywords || []),
  ].map(normalizeText).filter(Boolean);

  if (allSearchTerms.length === 0) return jobs;

  return jobs.filter((job) => {
    const titleNorm = normalizeText(job.title);
    const tagsNorm = job.tags.map(normalizeText).join(' ');
    const descNorm = normalizeText(job.description);
    const fullText = `${titleNorm} ${tagsNorm} ${descNorm}`;

    return allSearchTerms.some((term) => {
      if (titleNorm.includes(term) || tagsNorm.includes(term)) return true;
      const termTokens = term.split(' ').filter((t) => t.length > 2);
      if (termTokens.length > 0 && termTokens.every((t) => fullText.includes(t))) {
        return true;
      }
      return false;
    });
  });
}

function createMockSource(id: string, name: string, dataset: Job[], failSourceSetting?: string): JobSource {
  return {
    id,
    name,
    async search(query: SearchQuery): Promise<Job[]> {
      const isTest = typeof process !== 'undefined' && process.env?.NODE_ENV === 'test';
      const delay = isTest ? 10 : Math.floor(Math.random() * (1200 - 300 + 1)) + 300;
      await new Promise((resolve) => setTimeout(resolve, delay));

      if (failSourceSetting && failSourceSetting === id) {
        throw new Error(`Portál ${name} je momentálně nedostupný (simulovaná chyba).`);
      }

      return filterJobsByQuery(dataset, query);
    },
  };
}

